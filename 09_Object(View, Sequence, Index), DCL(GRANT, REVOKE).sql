CREATE OR REPLACE VIEW VIEW_PATIENT_INFO
AS
SELECT 	
		PATIENT_NAME
	 ,	DEPT_NAME
	 , 	DEPT_TYPE
	 ,	WARD_NAME
	 , 	DOCTOR_NAME
	 , 	GENDER
	 ,	BLOOD_TYPE
  FROM 
  		PATIENT
  JOIN
  		DEPT USING (DEPT_ID)
  JOIN 
  		WARD USING (WARD_ID)
  JOIN 
  		DOCTOR USING (DOCTOR_ID);

