SELECT 
		PATIENT_NAME
	 , 	DEPT_ID
	 ,  WARD_ID
	 ,	DOCTOR_ID
  FROM 
  		PATIENT;

SELECT
		DEPT_ID
	 ,	DEPT_NAME
  FROM 
  		DEPT;

SELECT 
		P.PATIENT_NAME
	 ,	D.DEPT_ID
	 ,	D.DEPT_NAME
  FROM 	
  		PATIENT P
	 ,	DEPT D
 WHERE
 		P.DEPT_ID = D.DEPT_ID
 ORDER
 	BY 
 		P.PATIENT_NAME;

SELECT 
		PATIENT_NAME
	 ,	DEPT_NAME
  FROM 	
  		PATIENT P
  JOIN  
  		DEPT D ON (P.DEPT_ID = D.DEPT_ID);

SELECT 
		PATIENT_NAME
	 ,  DEPT_NAME
  FROM 
  		PATIENT
  JOIN
  		DEPT USING(DEPT_ID);

SELECT
		PATIENT_NAME
	 ,	WARD_NAME
  FROM
  		PATIENT P
  JOIN
  		WARD W ON (P.WARD_ID = W.WARD_ID);

SELECT 
		PATIENT_NAME
	 ,	WARD_NAME
	 ,	DEPT_NAME
  FROM 	
  		PATIENT p
  JOIN 
  		WARD w ON(w.WARD_ID = p.WARD_ID)
  JOIN
 		DEPT d ON (p.DEPT_ID = d.DEPT_ID);

SELECT 
		PATIENT_NAME
	 ,  DOCTOR_NAME
  FROM 
  		PATIENT p
  JOIN
  		DOCTOR d ON (p.DOCTOR_ID = d.DOCTOR_ID);

SELECT
		PATIENT_NAME
	 ,	DOCTOR_NAME
  FROM 
  		PATIENT p
  	 ,	DOCTOR d
 WHERE 
 		p.DOCTOR_ID = d.DOCTOR_ID;

SELECT 
		PATIENT_NAME
	 ,	DEPT_NAME
  FROM 	
  		PATIENT p
  	 ,	DEPT d
 WHERE 
 		p.DEPT_ID = d.DEPT_ID 
   AND 
   		DEPT_TYPE = '외과계';

SELECT 
		PATIENT_NAME
	 ,  DOCTOR_NAME
  FROM 
  		PATIENT p
  LEFT
  JOIN 
  		DOCTOR d USING(DOCTOR_ID);

SELECT 
		PATIENT_NAME
	 ,	DOCTOR_NAME
  FROM 
  		PATIENT p 
 RIGHT		
  JOIN 
  		DOCTOR d USING(DOCTOR_ID);

SELECT
		NVL(PATIENT_NAME,'환자 미배정') "환자명"
	 ,	NVL(DOCTOR_NAME, '담당의 미배정') "담당의"
  FROM 
  		PATIENT p 
  FULL 	JOIN DOCTOR USING(DOCTOR_ID)
 ORDER
 	BY 
 		PATIENT_NAME ASC;

